"""Снятие лишних текстовых маркеров перед пунктами, оформляемыми шаблоном."""

import re

_TEXT_BULLET = re.compile(r"^([ \t]*)[-–—*•][ \t]+(?=[^\W\d_])", re.MULTILINE)


def normalize_list_formatting(text: str) -> str:
    """Убирает маркер перед словом, сохраняя текст, переносы и числовые знаки.

    Числовые префиксы и знак перед числом/валютой неоднозначны и остаются для
    обычной проверки. Функция применяется только к сгенерированным list-полям.
    """
    return _TEXT_BULLET.sub(r"\1", text)
